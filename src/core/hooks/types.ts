import type {
  CombatEvent,
  CombatHookId,
  CombatHookInfo,
  CombatantId,
  CombatState,
  Element,
  GearId,
  SkillId,
  Stats,
  StatusInstance,
} from '@/types/contracts';

/** Description of a single damaging hit, passed to hit-related hooks. */
export interface HitInfo {
  readonly attackerId: CombatantId;
  readonly targetId: CombatantId;
  /** Scaling kind: physical = atk vs def, magical = mag vs res. */
  readonly kind: 'physical' | 'magical';
  readonly element: Element;
  /** False for AoE (`allEnemies`) hits. */
  readonly singleTarget: boolean;
  /**
   * True when this hit was generated by a hook (a counter, a spell echo, …).
   * Hooks never react to hook-generated hits, which is what prevents chains.
   */
  readonly fromHook: boolean;
  /** HP actually lost by the target (0 for `onBeforeDamage`). */
  readonly amount: number;
  readonly skillId?: SkillId;
}

/**
 * A damaging skill that finished resolving against all of its targets. Dispatched
 * once per cast as `onAttackLanded` (with `hit` absent) after the per-target hits.
 */
export interface CastInfo {
  readonly actorId: CombatantId;
  readonly skillId: SkillId;
  /** Scaling kind of the cast skill (only damaging skills dispatch a cast). */
  readonly kind: 'physical' | 'magical';
  /** The chosen target for single-target skills; absent for AoE / self. */
  readonly targetId?: CombatantId;
  /** Targets the cast actually hit. */
  readonly hitTargets: readonly CombatantId[];
  readonly fromHook: boolean;
}

/**
 * The narrow slice of the combat machine a hook may use. Supplied by the
 * combat module at call time so hook files never import combat internals.
 */
export interface HookKernel {
  roll(state: CombatState): { readonly value: number; readonly state: CombatState };
  emit(state: CombatState, event: CombatEvent): CombatState;
  /** Effective stats (fusion / form / statuses applied). */
  stats(state: CombatState, id: CombatantId): Stats;
  /** A full basic attack (attack + damage events, armor, KO, hooks). */
  basicAttack(state: CombatState, actorId: CombatantId, targetId: CombatantId, opts: { readonly power: number; readonly fromHook: boolean }): CombatState;
  /** Whether `skillId` currently has at least one valid target for `actorId` (ignores AP). */
  canCast(state: CombatState, actorId: CombatantId, skillId: SkillId, targetId: CombatantId | undefined): boolean;
  /** Resolve a skill as a hook-generated action: no AP cost, no Sync, power × `powerScale`. */
  castSkill(state: CombatState, actorId: CombatantId, skillId: SkillId, targetId: CombatantId | undefined, opts: { readonly powerScale: number }): CombatState;
  heal(state: CombatState, targetId: CombatantId, amount: number): CombatState;
  changeAp(state: CombatState, targetId: CombatantId, delta: number): CombatState;
  gainSync(state: CombatState, id: CombatantId, amount: number): CombatState;
  applyStatus(state: CombatState, targetId: CombatantId, inst: StatusInstance): CombatState;
  /** Refill an unbroken fusion's armor pool by `amount` (capped at armorMax). */
  restoreArmor(state: CombatState, id: CombatantId, amount: number): CombatState;
}

export interface HookContext {
  readonly state: CombatState;
  readonly ownerId: CombatantId;
  readonly params: Readonly<Record<string, number>>;
  readonly sourceGear: GearId;
  readonly kernel: HookKernel;
  /** Present for per-hit onBeforeDamage / onDamaged / onAttackLanded / onKill. */
  readonly hit?: HitInfo;
  /** Present for the once-per-cast onAttackLanded dispatch of a damaging skill. */
  readonly cast?: CastInfo;
}

/**
 * One combat hook = one file exporting a `CombatHookImpl`, listed in
 * `hooks/index.ts`. `run` is pure: it returns the next state (or the same one
 * when it does nothing).
 */
export interface CombatHookImpl {
  readonly info: CombatHookInfo;
  run(ctx: HookContext): CombatState;
}

export interface HookRegistry {
  get(id: CombatHookId): CombatHookImpl | undefined;
  list(): readonly CombatHookInfo[];
}
