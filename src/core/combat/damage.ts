/**
 * Hit resolution, skill resolution, armor break, KO, healing, statuses and hook dispatch.
 *
 * Damage (before armor):
 *   physical: atk × power × 100 / (100 + def)
 *   magical : mag × power × 100 / (100 + res)
 *   × affinity (target, element)  × 0.5 if guarding  × 1.5 on crit  × variance (0.90..1.10)
 *   floored, minimum 1 (0 only when immune).
 * Crit chance = clamp(luck / 200, 0, 0.5). Two rng draws per hit: crit, then variance.
 *
 * Armor Break: a fused, unbroken host with armor > 0 has its armor chipped by
 * the FULL pre-armor damage while taking 70 % (`absorbedByArmor` = the 30 %).
 * Reaching 0 emits `armorBreak` and suppresses fusion for FUSION_BREAK_TURNS
 * of the host's own turns (see turns.ts).
 *
 * Hook dispatch order for one hit:
 *   target onBeforeDamage → damage → target onDamaged → attacker onAttackLanded (hit)
 *   → attacker onKill (if KO'd).
 * A damaging skill additionally dispatches attacker onAttackLanded once with `cast`
 * info after all of its targets resolved. Dead owners never run hooks, and hits /
 * casts generated by hooks carry `fromHook`, which every built-in hook ignores.
 */
import type {
  Combatant,
  CombatantId,
  CombatHookTrigger,
  CombatState,
  Element,
  SkillDef,
  SkillId,
  StatusInstance,
} from '@/types/contracts';
import { FUSION_BREAK_TURNS } from '@/types/contracts';
import type { CastInfo, HitInfo, HookKernel } from '../hooks';
import { clamp } from '../stats';
import { aliveOnSide, emit, gainSync, patchC, roll, SYNC_ON_HIT, type CombatCtx } from './context';
import { affinitiesFor, basicElementFor, clampVitals, statsFor } from './effective';

export const GUARD_FACTOR = 0.5;
export const CRIT_MULTIPLIER = 1.5;
export const ARMOR_ABSORB = 0.3;

export interface HitSpec {
  readonly kind: 'physical' | 'magical';
  readonly power: number;
  readonly element: Element;
  readonly singleTarget: boolean;
  readonly fromHook: boolean;
  readonly skillId?: SkillId;
}

export function makeKernel(ctx: CombatCtx): HookKernel {
  return {
    roll,
    emit: (s, e) => emit(s, e),
    stats: (s, id) => {
      const c = s.combatants[id];
      if (!c) throw new Error(`Unknown combatant ${id}`);
      return statsFor(ctx, c);
    },
    basicAttack: (s, actorId, targetId, opts) => basicAttack(ctx, s, actorId, targetId, opts),
    canCast: (s, actorId, skillId, targetId) => {
      const actor = s.combatants[actorId];
      const skill = ctx.db.skills[skillId];
      if (!actor || !actor.alive || !skill) return false;
      const t = skillTargets(s, actor, skill, targetId);
      return typeof t !== 'string' && t.length > 0;
    },
    castSkill: (s, actorId, skillId, targetId, opts) => {
      const actor = s.combatants[actorId];
      const skill = ctx.db.skills[skillId];
      if (!actor || !actor.alive || !skill) return s;
      return resolveSkill(ctx, s, actor, skill, targetId, { fromHook: true, powerScale: opts.powerScale });
    },
    heal: (s, id, amount) => heal(ctx, s, id, amount),
    changeAp: (s, id, delta) => changeAp(ctx, s, id, delta),
    gainSync: (s, id, amount) => gainSync(ctx, s, id, amount),
    applyStatus: (s, id, inst) => applyStatus(s, id, inst),
    restoreArmor: (s, id, amount) =>
      patchC(s, id, (c) =>
        c.fusion === null || c.fusion.broken || amount <= 0
          ? c
          : { ...c, fusion: { ...c.fusion, armor: Math.min(c.fusion.armorMax, c.fusion.armor + Math.floor(amount)) } },
      ),
  };
}

export function runHooks(
  ctx: CombatCtx,
  state: CombatState,
  ownerId: CombatantId,
  trigger: CombatHookTrigger,
  info: { readonly hit?: HitInfo; readonly cast?: CastInfo } = {},
): CombatState {
  const owner = state.combatants[ownerId];
  if (!owner || !owner.alive || owner.hooks.length === 0) return state;
  let s = state;
  const kernel = makeKernel(ctx);
  for (const h of owner.hooks) {
    if (!s.combatants[ownerId]?.alive) break;
    const impl = ctx.registry.get(h.hookId);
    if (!impl || impl.info.trigger !== trigger) continue;
    s = impl.run({
      state: s,
      ownerId,
      params: h.params,
      sourceGear: h.sourceGear,
      kernel,
      ...(info.hit ? { hit: info.hit } : {}),
      ...(info.cast ? { cast: info.cast } : {}),
    });
  }
  return s;
}

export function revertForm(ctx: CombatCtx, state: CombatState, id: CombatantId, reason: 'manual' | 'apDepleted' | 'maxTurns' | 'ko'): CombatState {
  const c = state.combatants[id];
  if (!c || c.dragon === null) return state;
  const s = emit(
    patchC(state, id, (x) => ({ ...x, dragon: null, sync: 0 })),
    { type: 'revert', actorId: id, reason },
  );
  return clampVitals(ctx, s, id);
}

export function knockOut(ctx: CombatCtx, state: CombatState, id: CombatantId): CombatState {
  let s = patchC(state, id, (x) => ({ ...x, hp: 0, alive: false, guarding: false, statuses: [] }));
  s = emit(s, { type: 'ko', targetId: id });
  return revertForm(ctx, s, id, 'ko');
}

export function basicAttack(
  ctx: CombatCtx,
  state: CombatState,
  actorId: CombatantId,
  targetId: CombatantId,
  opts: { readonly power: number; readonly fromHook: boolean },
): CombatState {
  const actor = state.combatants[actorId];
  if (!actor) return state;
  return performHit(ctx, state, actorId, targetId, {
    kind: 'physical',
    power: opts.power,
    element: basicElementFor(ctx, actor),
    singleTarget: true,
    fromHook: opts.fromHook,
  });
}

function affinityLabel(m: number): 'weak' | 'resist' | 'neutral' | 'immune' {
  if (m === 0) return 'immune';
  if (m > 1) return 'weak';
  if (m < 1) return 'resist';
  return 'neutral';
}

export function performHit(ctx: CombatCtx, state: CombatState, actorId: CombatantId, targetId: CombatantId, spec: HitSpec): CombatState {
  let s = emit(state, spec.skillId !== undefined
    ? { type: 'attack', actorId, targetId, skillId: spec.skillId, element: spec.element }
    : { type: 'attack', actorId, targetId, element: spec.element });

  const baseHit: HitInfo = {
    attackerId: actorId,
    targetId,
    kind: spec.kind,
    element: spec.element,
    singleTarget: spec.singleTarget,
    fromHook: spec.fromHook,
    amount: 0,
    ...(spec.skillId !== undefined ? { skillId: spec.skillId } : {}),
  };
  s = runHooks(ctx, s, targetId, 'onBeforeDamage', { hit: baseHit });

  const attacker = s.combatants[actorId];
  const target = s.combatants[targetId];
  if (!attacker || !target || !target.alive) return s;

  const as = statsFor(ctx, attacker);
  const ds = statsFor(ctx, target);
  const raw = spec.kind === 'physical'
    ? as.atk * spec.power * (100 / (100 + ds.def))
    : as.mag * spec.power * (100 / (100 + ds.res));
  const aff = affinitiesFor(ctx, target)[spec.element] ?? 1;
  const guard = target.guarding ? GUARD_FACTOR : 1;

  const critRoll = roll(s);
  s = critRoll.state;
  const crit = aff !== 0 && critRoll.value < clamp(as.luck / 200, 0, 0.5);
  const varRoll = roll(s);
  s = varRoll.state;
  const variance = 0.9 + varRoll.value * 0.2;

  const dmg = aff === 0 ? 0 : Math.max(1, Math.floor(raw * aff * guard * (crit ? CRIT_MULTIPLIER : 1) * variance));

  let amount = dmg;
  let absorbed = 0;
  let broke = false;
  let fusion = target.fusion;
  if (fusion !== null && !fusion.broken && fusion.armor > 0 && dmg > 0) {
    absorbed = Math.floor(dmg * ARMOR_ABSORB);
    amount = dmg - absorbed;
    const armor = Math.max(0, fusion.armor - dmg);
    broke = armor === 0;
    fusion = broke ? { ...fusion, armor: 0, broken: true, brokenTurns: FUSION_BREAK_TURNS } : { ...fusion, armor };
  }
  const hp = Math.max(0, target.hp - amount);
  s = patchC(s, targetId, (x) => ({ ...x, hp, fusion }));
  s = emit(s, { type: 'damage', targetId, amount, element: spec.element, crit, affinity: affinityLabel(aff), absorbedByArmor: absorbed });
  if (broke) {
    s = emit(s, { type: 'armorBreak', targetId });
    s = clampVitals(ctx, s, targetId);
  }
  const killed = hp === 0;
  if (killed) s = knockOut(ctx, s, targetId);
  else s = gainSync(ctx, s, targetId, SYNC_ON_HIT);

  const hit: HitInfo = { ...baseHit, amount };
  s = runHooks(ctx, s, targetId, 'onDamaged', { hit });
  s = runHooks(ctx, s, actorId, 'onAttackLanded', { hit });
  if (killed) s = runHooks(ctx, s, actorId, 'onKill', { hit });
  return s;
}

function opposite(side: Combatant['side']): Combatant['side'] {
  return side === 'party' ? 'enemy' : 'party';
}

/** Resolve a skill's targets (alive, relative to the actor's side), or a reason string. */
export function skillTargets(state: CombatState, actor: Combatant, skill: SkillDef, targetId: CombatantId | undefined): readonly CombatantId[] | string {
  const foes = opposite(actor.side);
  switch (skill.target) {
    case 'self':
      return [actor.id];
    case 'allEnemies':
      return aliveOnSide(state, foes).map((c) => c.id);
    case 'allAllies':
      return aliveOnSide(state, actor.side).map((c) => c.id);
    case 'enemy':
    case 'ally': {
      if (targetId === undefined) return 'A target is required.';
      const t = state.combatants[targetId];
      if (!t) return `Unknown target ${targetId}.`;
      if (!t.alive) return `${t.name} is down.`;
      const wanted = skill.target === 'enemy' ? foes : actor.side;
      if (t.side !== wanted) return `${skill.name} must target ${skill.target === 'enemy' ? 'a foe' : 'an ally'}.`;
      return [targetId];
    }
  }
}

/**
 * Resolve a skill. Player/AI casts pay AP and gain the skill's `syncGain` when it
 * lands; hook-generated casts (`fromHook`) are free, gain no Sync, scale power by
 * `powerScale`, and never dispatch hooks that could chain.
 */
export function resolveSkill(
  ctx: CombatCtx,
  state: CombatState,
  actor: Combatant,
  skill: SkillDef,
  targetId: CombatantId | undefined,
  opts: { readonly fromHook: boolean; readonly powerScale: number } = { fromHook: false, powerScale: 1 },
): CombatState {
  const targets = skillTargets(state, actor, skill, targetId);
  if (typeof targets === 'string') return state;
  let s = skill.apCost > 0 && !opts.fromHook ? changeAp(ctx, state, actor.id, -skill.apCost) : state;
  let landed = false;
  const hitTargets: CombatantId[] = [];
  const damaging = skill.kind === 'physical' || skill.kind === 'magical';
  const single = skill.target === 'enemy' || skill.target === 'ally' || skill.target === 'self';
  for (const tid of targets) {
    const t = s.combatants[tid];
    if (!t || !t.alive) continue;
    if (skill.kind === 'physical' || skill.kind === 'magical') {
      s = performHit(ctx, s, actor.id, tid, {
        kind: skill.kind,
        power: skill.power * opts.powerScale,
        element: skill.element,
        singleTarget: single,
        fromHook: opts.fromHook,
        skillId: skill.id,
      });
      hitTargets.push(tid);
    } else {
      s = emit(s, { type: 'attack', actorId: actor.id, targetId: tid, skillId: skill.id, element: skill.element });
      if (skill.kind === 'heal') {
        const a = s.combatants[actor.id];
        if (a) s = heal(ctx, s, tid, statsFor(ctx, a).mag * skill.power * opts.powerScale);
      }
    }
    landed = true;
    const inf = skill.inflicts;
    if (inf && s.combatants[tid]?.alive) {
      const r = roll(s);
      s = r.state;
      if (r.value < inf.chance) s = applyStatus(s, tid, { id: inf.status, turns: inf.turns, potency: inf.potency });
    }
    if (!s.combatants[actor.id]?.alive) break;
  }
  if (landed && !opts.fromHook && skill.syncGain !== undefined) s = gainSync(ctx, s, actor.id, skill.syncGain);
  if (damaging && hitTargets.length > 0 && (skill.kind === 'physical' || skill.kind === 'magical')) {
    const cast: CastInfo = {
      actorId: actor.id,
      skillId: skill.id,
      kind: skill.kind,
      hitTargets,
      fromHook: opts.fromHook,
      ...(single && targetId !== undefined ? { targetId } : {}),
    };
    s = runHooks(ctx, s, actor.id, 'onAttackLanded', { cast });
  }
  return s;
}

export function heal(ctx: CombatCtx, state: CombatState, targetId: CombatantId, amount: number): CombatState {
  const c = state.combatants[targetId];
  if (!c || !c.alive) return state;
  const max = statsFor(ctx, c).maxHp;
  const actual = Math.max(0, Math.min(Math.floor(amount), max - c.hp));
  const s = patchC(state, targetId, (x) => ({ ...x, hp: x.hp + actual }));
  return emit(s, { type: 'heal', targetId, amount: actual });
}

export function changeAp(ctx: CombatCtx, state: CombatState, targetId: CombatantId, delta: number): CombatState {
  const c = state.combatants[targetId];
  if (!c) return state;
  const max = statsFor(ctx, c).maxAp;
  const ap = clamp(c.ap + Math.trunc(delta), 0, max);
  if (ap === c.ap) return state;
  return emit(patchC(state, targetId, (x) => ({ ...x, ap })), { type: 'apChange', targetId, amount: ap - c.ap });
}

/** Apply (or refresh) a status. Same-id statuses are replaced, never stacked. */
export function applyStatus(state: CombatState, targetId: CombatantId, inst: StatusInstance): CombatState {
  const c = state.combatants[targetId];
  if (!c || !c.alive || inst.turns <= 0) return state;
  const s = patchC(state, targetId, (x) => ({ ...x, statuses: [...x.statuses.filter((st) => st.id !== inst.id), inst] }));
  return emit(s, { type: 'status', targetId, status: inst.id, applied: true });
}
